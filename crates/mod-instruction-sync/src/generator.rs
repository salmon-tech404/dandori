use sqlx::SqlitePool;

pub const AUTO_GENERATED_HEADER: &str = "<!-- Tệp sinh tự động bởi Dandori (Auto-generated by Dandori) - Không chỉnh sửa trực tiếp -->\n\n";

#[derive(Debug, thiserror::Error)]
pub enum GeneratorError {
    #[error("Lỗi cơ sở dữ liệu khi sinh hướng dẫn: {0}")]
    Database(#[from] sqlx::Error),
}

#[derive(Debug, sqlx::FromRow)]
struct TechProfileRow {
    category: String,
    key: String,
    value: String,
}

#[derive(Debug, sqlx::FromRow)]
struct SkillRow {
    name: String,
    description: String,
    content: String,
    embed_full: i64,
}

pub fn default_target_filename(provider: &str) -> &'static str {
    match provider.to_lowercase().as_str() {
        "claude" => "CLAUDE.md",
        "cursor" => ".cursorrules",
        _ => "AGENTS.md",
    }
}

#[expect(
    clippy::too_many_lines,
    reason = "Hàm tổng hợp nội dung hướng dẫn từ hồ sơ kỹ thuật và danh sách kỹ năng"
)]
pub async fn generate_instruction_content(
    pool: &SqlitePool,
    workspace_id: &str,
    project_id: &str,
    provider: &str,
    role: Option<&str>,
) -> Result<(String, usize, usize), GeneratorError> {
    let mut buffer = String::new();
    buffer.push_str(AUTO_GENERATED_HEADER);
    buffer.push_str(&format!(
        "# Dandori Instructions (Provider: {})\n\n",
        provider
    ));

    // 1. Hồ sơ kỹ thuật (Tech Profile)
    let tech_profiles: Vec<TechProfileRow> = match sqlx::query_as::<_, TechProfileRow>(
        r#"
        SELECT category, key, value
        FROM m_tech_profile_entry
        WHERE project_id = ?
        ORDER BY category ASC, sort_order ASC, key ASC
        "#,
    )
    .bind(project_id)
    .fetch_all(pool)
    .await
    {
        Ok(rows) => rows,
        Err(e) => {
            tracing::warn!("Không thể đọc m_tech_profile_entry: {}", e);
            Vec::new()
        }
    };

    let tech_count = tech_profiles.len();
    if !tech_profiles.is_empty() {
        buffer.push_str("## 1. Hồ sơ kỹ thuật dự án\n\n");
        let mut current_cat = String::new();
        for item in &tech_profiles {
            if item.category != current_cat {
                current_cat = item.category.clone();
                buffer.push_str(&format!("### {}\n", current_cat));
            }
            buffer.push_str(&format!("- **{}**: {}\n", item.key, item.value));
        }
        buffer.push('\n');
    }

    // 2. Kỹ năng đã duyệt (Approved Skills)
    let role_filter = role.unwrap_or("");
    let skills: Vec<SkillRow> = match sqlx::query_as::<_, SkillRow>(
        r#"
        SELECT DISTINCT s.name, s.description, s.content, COALESCE(b.embed_full, 0) as embed_full
        FROM m_skills_md_skill s
        LEFT JOIN m_skills_md_binding b ON s.id = b.skill_id
            AND (b.project_id = ? OR b.project_id IS NULL)
            AND (b.role = ? OR b.role IS NULL OR b.role = '')
        WHERE s.workspace_id = ? AND s.status = 'approved'
        ORDER BY s.name ASC
        "#,
    )
    .bind(project_id)
    .bind(role_filter)
    .bind(workspace_id)
    .fetch_all(pool)
    .await
    {
        Ok(rows) => rows,
        Err(e) => {
            tracing::warn!("Không thể đọc m_skills_md_skill: {}", e);
            Vec::new()
        }
    };

    let skills_count = skills.len();
    if !skills.is_empty() {
        buffer.push_str("## 2. Kỹ năng và quy chuẩn (Skills)\n\n");
        for skill in &skills {
            buffer.push_str(&format!("### {}\n", skill.name));
            buffer.push_str(&format!("{}\n\n", skill.description));
            if skill.embed_full != 0 && !skill.content.trim().is_empty() {
                buffer.push_str("```markdown\n");
                buffer.push_str(&skill.content);
                if !skill.content.ends_with('\n') {
                    buffer.push('\n');
                }
                buffer.push_str("```\n\n");
            }
        }
    }

    Ok((buffer, tech_count, skills_count))
}
